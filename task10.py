
# Исходный русский текст
text_ru = """Теория информации изучает способы представления, хранения и передачи сообщений. Любое сообщение можно рассматривать как последовательность символов, каждый из которых появляется с определённой вероятностью. Если одни символы встречаются часто, а другие редко, можно использовать код переменной длины: частым символам назначать короткие кодовые слова, а редким — более длинные. Именно этот принцип лежит в основе алгоритма Хаффмана. Сначала подсчитывают частоты всех символов, затем выбирают два символа или узла с наименьшими весами и объединяют их в новый узел. Процесс повторяется, пока не останется одно дерево. Путь от корня к листу задаёт двоичный код символа. Полученный код является префиксным, поэтому сообщение можно декодировать без специальных разделителей между кодовыми словами. На практике важно учитывать не только длину закодированных данных, но и дополнительные сведения, необходимые для восстановления исходного текста. К ним относятся таблица кодов, длина исходного сообщения и заполнение последнего байта нулями. Для коротких сообщений служебные данные могут оказаться больше экономии, поэтому сжатие не всегда уменьшает файл. Для больших сообщений с неравномерным распределением символов кодирование Хаффмана может дать заметный выигрыш. Результат зависит от состава текста и выбранного способа хранения."""

# Подсчёт частот
freq = Counter(text_ru)

# Построение дерева Хаффмана
tree, codes = build_huffman(freq)

# Кодирование
bits = encode(text_ru, codes)

# Декодирование
decoded = decode(bits, tree)

# Проверка
assert decoded == text_ru

# Расчёт вероятностей
N = len(text_ru)
p = {s: n / N for s, n in freq.items()}

# Энтропия
H = -sum(x * math.log2(x) for x in p.values())

# Средняя длина
L = sum(p[s] * len(codes[s]) for s in freq)

# Эффективность и избыточность
eta = H / L * 100
R = 100 - eta

# Размеры
original_size = len(text_ru.encode("utf-8"))
packed_size = (len(bits) + 7) // 8
padding = packed_size * 8 - len(bits)

# Размер таблицы кодов:
# символ UTF-8 + длина кода + упакованный код
table_size = sum(
    len(s.encode("utf-8")) + 1 + (len(codes[s]) + 7) // 8
    for s in codes
)

# Служебные данные:
# 4 байта на длину текста и 2 байта на алфавит
service_size = table_size + 4 + 2

total_size = packed_size + service_size

# Вывод результатов
print("Количество символов:", N)
print("Различных символов:", len(freq))
print("Частоты:", freq)
print("Коды Хаффмана:", codes)

print("Энтропия:", round(H, 4))
print("Средняя длина:", round(L, 4))
print("Эффективность:", round(eta, 2), "%")
print("Избыточность:", round(R, 2), "%")

print("Исходный размер:", original_size, "байт")
print("Длина битового потока:", len(bits), "бит")
print("Упакованный размер:", packed_size, "байт")
print("Заполнение:", padding, "бит")
print("Размер таблицы:", table_size, "байт")
print("Служебные данные:", service_size, "байт")
print("Общий размер:", total_size, "байт")

print("Коэффициент сжатия:", round(original_size / total_size, 3))
print("Сокращение:", round(
    (1 - total_size / original_size) * 100, 2
), "%")

print("Проверка декодирования:", decoded == text_ru)
